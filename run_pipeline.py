"""Build the RAG pipeline end to end: acquire -> chunk -> embed -> index.

This is the engineering track's single entry point. Running it from a clean
checkout downloads the arXiv corpus, chunks it, embeds every chunk, builds the
FAISS index, and saves everything to `data/` — with no API key required (all of
this is local). After it finishes, retrieval works and the evaluation can run.

    python run_pipeline.py

It is deterministic and idempotent: run it again and you get the same index.
"""

from __future__ import annotations

import random
import time

import numpy as np

from src import acquisition, chunking, config
from src.vectorstore import VectorStore


def main() -> None:
    random.seed(config.SEED)
    np.random.seed(config.SEED)
    config.ensure_dirs()

    t0 = time.time()
    print("1/4  Acquiring arXiv corpus ...")
    papers = acquisition.acquire()
    print(f"     {len(papers)} papers "
          f"({sum(p.redistributable for p in papers)} redistributable) "
          f"-> {config.PAPERS_FILE}")

    print("2/4  Chunking ...")
    chunks = chunking.chunk_papers(papers)
    chunking.save_chunks(chunks)
    print(f"     {len(chunks)} chunks -> {config.CHUNKS_FILE}")

    print("3/4  Embedding + building FAISS index ...")
    frame = chunking.load_chunks()
    store = VectorStore.build(frame)
    print(f"     {store.size} vectors, dim {config.EMBED_DIM}")

    print("4/4  Saving index ...")
    store.save()
    print(f"     -> {config.FAISS_INDEX_FILE}")

    # The corpus figure belongs to the build, not the benchmark: it describes the
    # papers that were downloaded, so it goes stale the moment they change and
    # should be regenerated by the same command that changes them.
    from src import figures
    figures.corpus_figure(papers)
    print(f"     -> {config.FIGURES_DIR / 'deck' / 'deck_corpus_categories.png'}")

    print(f"Done in {time.time() - t0:.1f}s. Retrieval is ready.")


if __name__ == "__main__":
    main()
